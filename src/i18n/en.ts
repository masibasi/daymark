// Literal strings widen to `string`, readonly arrays to plain arrays; function signatures and object keys are kept, so ko.ts can't miss or add a key.
type Widen<T> = T extends string ? string : T extends (...args: infer A) => string ? (...args: A) => string : T extends readonly (infer U)[] ? readonly Widen<U>[] : { -readonly [K in keyof T]: Widen<T[K]> };
export type Dictionary = Widen<typeof en>;
